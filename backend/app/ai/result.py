from __future__ import annotations

from app.models.enums import (
    RecommendationCategory,
    RecommendationComponent,
    RecommendationPriority,
)
from pydantic import BaseModel, Field

# ==========================================================
# PROJECT FILES
# ==========================================================

class ProjectFile(BaseModel):
    """
    Represents a single file from the uploaded project.
    """

    path: str = Field(
        description="Relative path of the file inside the project.",
    )

    content: str = Field(
        description="Text content of the file.",
    )


class ProjectFiles(BaseModel):
    """
    Represents all files prepared for AI analysis.
    """

    project_name: str = Field(
        description="Name of the analyzed project.",
    )

    root_path: str = Field(
        description="Root storage path of the project.",
    )

    files: list[ProjectFile] = Field(
        default_factory=list,
        description="List of project files included in the analysis.",
    )


# ==========================================================
# RECOMMENDATIONS
# ==========================================================

class RecommendationResult(BaseModel):
    """
    Represents a single AI-generated recommendation.
    """

    title: str = Field(
        description="Short and descriptive recommendation title."
    )

    description: str = Field(
        description="Detailed explanation of the recommendation and why it is important."
    )

    component: RecommendationComponent = Field(
        description="Project component affected by this recommendation."
    )

    priority: RecommendationPriority = Field(
        description="Priority level indicating the importance of implementing this recommendation."
    )

    category: RecommendationCategory = Field(
        description="Category describing the type of recommendation."
    )


# ==========================================================
# ARCHITECTURE
# ==========================================================

class DependencyResult(BaseModel):
    """
    Represents a dependency relationship between two components.
    """

    source: str = Field(
        description="Component that depends on another component."
    )

    target: str = Field(
        description="Component being depended on."
    )


class ArchitectureResult(BaseModel):
    """
    Represents the architecture analysis result.
    """

    diagram_data: dict[str, object] = Field(
        default_factory=dict,
        description="Structured architecture diagram data representing the components and their relationships."
    )

    layers: list[str] = Field(
        default_factory=list,
        description="List of architectural layers detected."
    )

    dependencies: list[DependencyResult] = Field(
        default_factory=list,
        description="List of dependencies between components."
    )


# ==========================================================
# ROADMAP
# ==========================================================

class RoadmapResult(BaseModel):
    """
    Represents the modernization roadmap generated by AI.
    """

    roadmap_data: dict[str, object] = Field(
        default_factory=dict,
        description="Structured modernization roadmap including phases, milestones, priorities, and estimated implementation order."
    )


# ==========================================================
# COMPLETE ANALYSIS RESULT
# ==========================================================

class AnalysisResult(BaseModel):
    """
    Complete structured result returned by the AI analysis engine.
    """

    summary: str = Field(
        description="High-level summary describing the purpose, structure, and overall condition of the analyzed project."
    )

    detected_technologies: list[str] = Field(
        default_factory=list,
        description="List of technologies, tools, databases, servers, and platforms detected in the project.",
    )

    programming_languages: list[str] = Field(
        default_factory=list,
        description="List of programming languages detected in the project.",
    )

    frameworks: list[str] = Field(
        default_factory=list,
        description="Frameworks and libraries identified in the project.",
    )

    architecture: ArchitectureResult = Field(
        description="Complete architectural analysis of the project."
    )

    documentation: str = Field(
        description="Technical documentation summarizing the project's architecture, technologies, important components, and observations."
    )

    roadmap: RoadmapResult = Field(
        description="Modernization roadmap proposing the recommended migration strategy."
    )

    recommendation: RecommendationResult = Field(
        description="List of actionable recommendations to improve the project's architecture, maintainability, security, and modernization."
    )

class ProjectContext(BaseModel):

    project_name: str

    content: str

class ChatMessage(BaseModel):
    """
    Represents a single message in the assistant conversation.
    """

    role: str = Field(
        description="Role of the message sender.",
    )

    content: str = Field(
        description="Message content.",
    )

class ConversationHistory(BaseModel):
    """
    Represents the conversation history with the AI assistant.
    """

    messages: list[ChatMessage] = Field(
        default_factory=list,
        description="Ordered conversation messages.",
    )


class AssistantRequest(BaseModel):
    """
    Request payload for the AI assistant chat endpoint.
    """

    message: str = Field(
        description="Latest user message.",
    )

    history: ConversationHistory | None = Field(
        default=None,
        description="Previous conversation history.",
    )


class AssistantResponse(BaseModel):
    """
    Represents the AI assistant response.
    """

    answer: str = Field(
        description="Assistant reply.",
    )